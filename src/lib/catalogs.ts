export function findModelSpec(modelId: string): ModelSpec {
  const exact = MODEL_CATALOG.find((m) => m.id === modelId);
  if (exact) return exact;
  const lower = modelId.toLowerCase();
  if (lower.includes('sonnet') || lower.includes('claude')) {
    return MODEL_CATALOG.find((m) => m.id === 'claude-sonnet-4-6') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('gemini') && lower.includes('pro')) {
    return MODEL_CATALOG.find((m) => m.id === 'gemini-2.5-pro') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('gemini')) {
    return MODEL_CATALOG.find((m) => m.id === 'gemini-2.5-flash') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('codestral') || lower.includes('mistral')) {
    return MODEL_CATALOG.find((m) => m.id === 'codestral-latest') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('qwen')) {
    return MODEL_CATALOG.find((m) => m.id === 'qwen-2.5-coder-32b') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('deepseek')) {
    return MODEL_CATALOG.find((m) => m.id === 'deepseek-r1') ?? MODEL_CATALOG[0];
  }
  if (lower.includes('llama')) {
    return MODEL_CATALOG.find((m) => m.id === 'llama-3.3-70b-versatile') ?? MODEL_CATALOG[0];
  }
  return MODEL_CATALOG[0]; // Default 100% Free Gemini 2.5 Flash spec ($0.00)
}
